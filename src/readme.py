"""Render README.md from the outputs, so every number in it traces to a claim or output file."""

from __future__ import annotations

from common import ROOT, load_brief, read_json, settings


def main() -> None:
    s = settings()
    c = {x["id"]: x["text"] for x in read_json("outputs/claims_rendered.json")["claims"]}
    brief = load_brief()
    dec = read_json("outputs/decision.json")
    rep = read_json("outputs/validation_report.json")
    fz = read_json("outputs/brief_freeze.json")
    live = s["site"]["live_url"]
    per = s["periods"]
    g = brief["guardrails"]["delinquent_per_1000_randomized"]
    lines = [
        "# Loan Funnel & KYC Experiment (simulated data)",
        "",
        "End-to-end funnel and A/B test analysis on a **simulated** loan-application event log: find the leak in "
        "SQL, pre-register and analyse a simplified-KYC experiment, protect credit quality with non-inferiority "
        "guardrails, and decide under a rule frozen before any data existed.",
        "",
        f"**Site:** {live if live else 'Not yet available (deploy pending)'} · **Author:** "
        f"[{s['site']['author']}]({s['site']['github_url']}) · [LinkedIn]({s['site']['linkedin_url']})",
        "",
        "> **Simulated-data notice.** All data is generated by `src/simulate.py`. *Pebble Credit* is a fictional "
        "lender. Effects were planted in the generator, so this project demonstrates the analysis method and shows "
        "it recovers the planted truth. It is not a real company's result.",
        "",
        "| Home | Experiment | Guardrails |",
        "|---|---|---|",
        "| ![Home](tests/screenshots/home-1440.png) | ![Experiment](tests/screenshots/experiment-1440.png) | "
        "![Guardrails](tests/screenshots/guardrails-1440.png) |",
        "",
        "## Business question",
        "Many applicants abandon the loan journey. Where is the biggest leak, does a simpler KYC flow fix it, and "
        "does any conversion gain come at the cost of worse credit quality?",
        "",
        "## Simulation design",
        f"- {per['pre_period_weeks']}-week pre-period (baseline funnel) + {per['experiment_weeks']}-week experiment; "
        "users randomized 50/50 by seeded hash at their first KYC start.",
        "- Tables: `users`, `events` (application_started → kyc_started → kyc_completed → decision_made → "
        "loan_disbursed), `loans` (first-EMI 30+ DPD flag).",
        "- Segment-varying conversion, day-of-week seasonality, log-normal stage gaps, legitimate KYC retries, and a "
        "**selection effect**: marginal applicants let through by the simpler flow are declined and go "
        "early-delinquent more often.",
        "- Injected data-quality issues (duplicates, out-of-order timestamps, null devices, missing steps) with exact "
        "counts, plus a separate broken-assignment dataset used only to prove the SRM check works.",
        "- Every parameter and its rationale: `config/simulation.yaml`.",
        "",
        "## Funnel findings (pre-period)",
        f"- {c['FUN-001']}",
        f"- {c['FUN-002']}",
        f"- {c['FUN-003']}",
        f"- {c['FUN-004']}",
        "",
        "## Experiment design",
        f"- Pre-registration `config/experiment_brief.yaml`, frozen {fz['frozen_at_utc']} (SHA-256 `{fz['sha256'][:12]}…`) "
        "**before data was simulated**; the analysis refuses to run if it is missing or edited.",
        f"- Primary metric: {brief['primary_metric']['name']} = {brief['primary_metric']['numerator']} ÷ "
        f"{brief['primary_metric']['denominator']} (intention-to-treat).",
        f"- Decision guardrail: {g['name']}, margin +{g['margin']} derived by break-even unit economics from the "
        "business MDE and control-arm baseline rates only (no planted effects in the formula).",
        f"- {c['PWR-001']}",
        f"- {c['PWR-002']}",
        "",
        "## Results",
        f"- {c['EXP-002']}",
        f"- **Primary:** {c['EXP-001']}",
        f"- **Ground truth:** {c['EXP-003']}",
        f"- **Secondary:** {c['EXP-004']}",
        f"- **Decision guardrail:** {c['GRD-001']}",
        f"- {c['GRD-002']}",
        f"- {c['GRD-003']}",
        f"- {c['EXP-005']}",
        "",
        "## Decision and rollout plan",
        f"**{dec['decision_label']}.** {c['DEC-001']}",
        "",
    ]
    lines += [f"- {'✓' if x['met'] else '✗'} {x['condition']}" for x in dec["conditions"]]
    lines += [
        "",
        "Full one-page memo with the staged rollout plan, 30/60/90-day delinquency monitoring and rollback "
        "triggers: [`memo/recommendation.md`](memo/recommendation.md).",
        "",
        "## Method validation",
        f"- {c['VAL-001']}",
        f"- {c['VAL-002']}",
        f"- {c['VAL-003']}",
        f"- {c['VAL-004']}",
        f"- {c['VAL-005']}",
        f"- Cross-stage validation: {rep['checks_passed']}/{rep['checks_total']} checks passing "
        "(`outputs/validation_report.json`).",
        "",
        "## Limitations",
        "- **Simulated data:** demonstrates the method; real behaviour is messier.",
        "- **Outcome maturity:** early delinquency covers only the first EMI; later losses are unobserved.",
        "- **Novelty effect:** a short test may overstate a lift that fades.",
        "- **Single experiment:** one run of one test; the validation simulations show how often a run like this "
        "would mislead.",
        "",
        "## How to reproduce",
        "```bash",
        "python make.py setup      # or: make setup (Python 3.11 venv + requirements)",
        "python make.py all        # simulate → … → validate → export-web",
        "python make.py test       # pytest",
        "cd web && npm ci && npm run lint && npm run typecheck && npm test && npm run build && npm run e2e",
        "```",
        "Seed 42 everywhere; two runs produce byte-identical outputs. `python make.py feasibility` and "
        "`src/brief.py` are one-off pre-simulation steps (the brief refuses to be overwritten).",
        "",
        "## Structure",
        "```",
        "config/      simulation.yaml (ground truth) · experiment_brief.yaml (frozen) · settings.yaml",
        "sql/         01_clean_events … 07_guardrails (DuckDB)",
        "src/         simulate, ingest, clean, funnel, power, experiment, guardrails, segments,",
        "             validation_sims, decision, claims, validate, export_web, readme",
        "outputs/     aggregated CSV/JSON, claims registry, resume bullets (committed)",
        "memo/        recommendation.md (generated)",
        "tests/       pytest suites + Playwright screenshots",
        "web/         Next.js static site (Vercel root directory)",
        "```",
        "",
    ]
    (ROOT / "README.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("README.md written")


if __name__ == "__main__":
    main()
